def add_numbers(a, b):
    """Adds two numbers and returns the result."""
    return a + b

def greet_user(name):
    """Returns a greeting string."""
    return f"Hello, {name}!"

def subtract_numbers(a, b):
    """Subtracts b from a and returns the result."""
    return a - b

def multiply_numbers(a, b):
    """Multiplies two numbers and returns the result."""
    return a * b
